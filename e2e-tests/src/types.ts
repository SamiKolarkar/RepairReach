// ==========================================
// 4. Availability & Scheduling Domain
// ==========================================

export type SlotReason =
  | 'AVAILABLE'
  | 'BOOKED'
  | 'OUT_OF_HOURS'
  | 'SUNDAY_CLOSING'
  | 'AFTERNOON_BREAK'
  | 'TECHNICIAN_UNAVAILABLE'
  | 'HOLIDAY'
  | string;

export interface AvailabilitySlot {
  slotId: string;
  startTime: string; // e.g. '10:00' or ISO time '10:00:00'
  endTime: string; // e.g. '11:00' or ISO time '11:00:00'
  available: boolean;
  reason?: SlotReason;
}

export interface AvailabilityResponse {
  date: string; // YYYY-MM-DD
  serviceId: string;
  slots: AvailabilitySlot[];
}

