// ==========================================
// 1. RFC 7807 Problem Details Error Model
// ==========================================

export interface InvalidParam {
  name: string;
  reason: string;
  value?: unknown;
}

export interface AlternativeSlot {
  slotId: string;
  startTime: string;
  endTime: string;
}

export interface ProblemDetails {
  /** A URI reference that identifies the problem type */
  type: string;
  /** A short, human-readable summary of the problem type */
  title: string;
  /** The HTTP status code generated by the origin server for this occurrence of the problem */
  status: number;
  /** Application-specific error code (e.g., 'SLOT_UNAVAILABLE', 'VALIDATION_FAILED', 'NOT_FOUND') */
  code?: string;
  /** A human-readable explanation specific to this occurrence of the problem */
  detail?: string;
  /** A URI reference that identifies the specific occurrence of the problem */
  instance?: string;
  /** Unique request trace / correlation identifier */
  correlationId?: string;
  /** Timestamp when error was produced */
  timestamp?: string;
  /** Field-level validation error details */
  invalidParams?: InvalidParam[];
  /** Alternative slots offered in 409 conflict scenarios */
  alternatives?: AlternativeSlot[];
  /** Extension members */
  [key: string]: unknown;
}

// Standard Error Codes
